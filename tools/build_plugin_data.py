"""Generates data for the plugin.

  py -3.10 tools/build_plugin_data.py

Outputs
  plugin/src/generated/strings.rs  screen strings (tools/strings.py) -> key constants and 9 language tables
  plugin/assets/names.<language>.bin   names of armor, decorations, skill trees, skills, items (one file per language)
  plugin/src/generated/data.rs     category tabs, armor crafting materials/prices and other values not in simdata.bin
  plugin/assets/font.otf           font with only the characters shown on screen (NotoSansCJKkr subset)

names.bin format (little endian)
  'SKN2' + u8 table count
  Per table: u16 count n, n u16 ids (ascending), u32 pool size, n+1 u32 offsets, string pool (UTF-8)
  Table order: 0 armor, 1 decorations, 2 skill trees, 3 skills, 4 items
"""
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import gamedb  # noqa: E402
import strings  # noqa: E402

PLUGIN = ROOT / 'plugin'
GEN = PLUGIN / 'src' / 'generated'
ASSETS = PLUGIN / 'assets'
SOURCE_FONT = ROOT.parent / 'MHGU-Wishlist' / 'assets' / 'NotoSansCJKkr-Regular.otf'
# The font holds the characters of all 9 languages, so changing the language never needs another font
FONT_LANGS = list(range(9))


def rust_key(k):
    return ''.join(c if c.isalnum() else '_' for c in k).upper()


def write_strings():
    keys = list(strings.STRINGS)
    lines = ['//! Generated by tools/build_plugin_data.py from tools/strings.py. Do not edit.',
             '#![allow(dead_code)]', f'pub const COUNT: usize = {len(keys)};']
    for i, k in enumerate(keys):
        lines.append(f'pub const {rust_key(k)}: u16 = {i};')
    # One table per game language (0 English .. 8 Spanish); keys without a translation use English
    lines.append('pub static TABLES: [[&str; COUNT]; 9] = [')
    out = []
    for lang in range(9):
        lines.append('    [')
        for k in keys:
            v = strings.string(k, lang)
            lines.append('        ' + rust_str(v) + ',')
            out += v if isinstance(v, list) else [v]
        lines.append('    ],')
    lines.append('];')
    (GEN / 'strings.rs').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    return out


def rust_str(s):
    # List values (dropdown entries etc.) are joined with \x1f and split in the plugin.
    if isinstance(s, list):
        s = '\x1f'.join(s)
    # Replace backslashes first, then insert \x1f as a Rust escape (in the other order \u{1f} comes out as text)
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\x1f', '\\u{1f}') + '"'


def write_names(db):
    tables = [
        {i: a['names'] for i, a in db.armor.items()},
        {i: j['names'] for i, j in db.jewels.items()},
        {i: n for i, n in db.trees.items()},
        {s['id']: s['names'] for s in db.skills},
        dict(db.item_names),
    ]
    # One file per language: the plugin reads only the current language's file (all 9 languages would be 1.5 MB).
    total = 0
    for lang, code in enumerate(gamedb.LANGS):
        out = bytearray(b'SKN2') + bytes([len(tables)])
        for t in tables:
            ids = sorted(t)
            out += struct.pack('<H', len(ids)) + b''.join(struct.pack('<H', i) for i in ids)
            pool, offs = bytearray(), [0]
            for i in ids:
                pool += (t[i][lang] or t[i][0] or '').encode('utf-8')
                offs.append(len(pool))
            out += struct.pack('<I', len(pool)) + b''.join(struct.pack('<I', o) for o in offs) + pool
        (ASSETS / f'names.{code}.bin').write_bytes(out)
        total += len(out)
    (ASSETS / 'names.bin').unlink(missing_ok=True)
    out = range(total)
    texts = []
    for t in tables:
        for names in t.values():
            texts += [names[l] for l in FONT_LANGS if names[l]]
    return texts, len(out)


def write_data(db):
    lines = ['//! Generated by tools/build_plugin_data.py. Do not edit.', '#![allow(dead_code)]']
    # Category tabs: (key, tree ranges)
    lines.append('pub static CATEGORIES: &[(&str, &[(u16, u16)])] = &[')
    for key, ranges in gamedb.CATEGORIES:
        lines.append(f'    ("{key}", &[' + ', '.join(f'({a}, {b})' for a, b in ranges) + ']),')
    lines.append('];')
    # Armor crafting materials: (armor id, price, material start, material count), material: (item id, game item number, quantity)
    mats, rows = [], []
    for aid in sorted(db.armor):
        a = db.armor[aid]
        rows.append((aid, a['price'], len(mats), len(a['mats'])))
        for item, qty in a['mats']:
            mats.append((item, db.game_items.get(item, 0), qty))
    lines.append('pub static ARMOR_COST: &[(u16, u32, u16, u8)] = &[')
    lines += [f'    ({a}, {p}, {s}, {n}),' for a, p, s, n in rows]
    lines.append('];')
    lines.append('pub static MATERIALS: &[(u16, u16, u8)] = &[')
    lines += [f'    ({i}, {g}, {q}),' for i, g, q in mats]
    lines.append('];')
    # Game item number -> decoration item id, sorted by game number (to read the decorations of equipped gear)
    lines.append('pub static JEWEL_GAME: &[(u16, u16)] = &[')
    lines += [f'    ({g}, {j}),' for g, j in sorted((g, j) for j, g in db.jewel_game.items())]
    lines.append('];')
    (GEN / 'data.rs').write_text('\n'.join(lines) + '\n', encoding='utf-8')


def write_font(texts):
    from fontTools import subset
    from fontTools.ttLib import TTFont
    chars = {ord(c) for t in texts for c in t if not c.isspace()}
    chars |= set(range(0x20, 0x7f)) | {0x2026, 0x00b7, 0x2192, 0x00d7, 0x2014, 0x00b1, 0x0394, 0x3010, 0x3011, 0xff0b}
    # Symbols drawn directly by the plugin code (arrows, minus etc.): collected from strings in the drawing code
    for src in (PLUGIN / 'src').glob('*.rs'):
        for line in src.read_text(encoding='utf-8').splitlines():
            code = line.split('//')[0]
            chars |= {ord(c) for c in code if ord(c) > 0x7f and not c.isspace()}
    font = TTFont(SOURCE_FONT, recalcTimestamp=False)
    opts = subset.Options()
    opts.layout_features = ['*']
    opts.notdef_glyph = True
    opts.notdef_outline = True
    opts.recommended_glyphs = True
    worker = subset.Subsetter(options=opts)
    worker.populate(unicodes=chars)
    worker.subset(font)
    path = ASSETS / 'font.otf'
    font.save(path)
    return len(chars), path.stat().st_size


ATLAS_CELL = 64
ATLAS_COLS = 12


def write_atlas():
    """Packs the preview assets/ui pictures (3 button layouts, parts, charm, decoration, materials) into one RGBA image.
    White parts are tinted by multiplying a color like the game does (rarity colors etc.). Cells are 64 px; pictures are fitted inside."""
    from PIL import Image
    import json
    src = ROOT / 'assets' / 'ui'
    names = sorted(p.stem for p in src.glob('*.png'))
    rows = (len(names) + ATLAS_COLS - 1) // ATLAS_COLS
    atlas = Image.new('RGBA', (ATLAS_COLS * ATLAS_CELL, rows * ATLAS_CELL), (0, 0, 0, 0))
    for i, n in enumerate(names):
        im = Image.open(src / f'{n}.png').convert('RGBA').resize((ATLAS_CELL, ATLAS_CELL), Image.LANCZOS)
        atlas.paste(im, ((i % ATLAS_COLS) * ATLAS_CELL, (i // ATLAS_COLS) * ATLAS_CELL))
    (ASSETS / 'atlas.rgba').write_bytes(atlas.tobytes())
    items = json.loads((src / 'items.json').read_text(encoding='utf-8'))
    lines = ['//! Generated by tools/build_plugin_data.py. Do not edit.', '#![allow(dead_code)]',
             f'pub const CELL: u32 = {ATLAS_CELL};', f'pub const COLS: u32 = {ATLAS_COLS};',
             f'pub const WIDTH: u32 = {atlas.width};', f'pub const HEIGHT: u32 = {atlas.height};',
             'pub static NAMES: &[&str] = &[' + ', '.join(f'"{n}"' for n in names) + '];',
             '/// Game item number -> (picture number, color 0xRRGGBB, rarity). The picture is "item-<number>" in the atlas',
             'pub static ITEMS: &[(u16, u32, u8)] = &[']
    lines += [f'    ({i}, 0x{c[1:]}, {r}),' for i, c, r in items]
    lines.append('];')
    (GEN / 'atlas.rs').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    return atlas.size


def main():
    GEN.mkdir(parents=True, exist_ok=True)
    ASSETS.mkdir(parents=True, exist_ok=True)
    db = gamedb.GameData()
    ui_texts = write_strings()
    name_texts, names_size = write_names(db)
    write_data(db)
    n, size = write_font(ui_texts + name_texts)
    atlas = write_atlas()
    print(f'strings {len(strings.STRINGS)}, names {names_size} bytes, font {n} chars {size} bytes, atlas {atlas}')


if __name__ == '__main__':
    main()
